// EventGuide documents an event for other developers: what it is, how to
// dispatch it, its listeners, and (with a trace) what really happened.
func EventGuide(site string, ev Event, trace *Trace, from []Location) ([]byte, error) {
	d := newDoc(short(ev.Class), "Event guide · "+site, site)
	d.para(firstNonEmpty(ev.Doc, "An event in "+site+". Dispatching it runs the listeners below, in order."))
	d.kv([][2]string{
		{"Class", ev.Class},
		{"Defined in", fmt.Sprintf("%s:%d", ev.File, ev.Line)},
		{"Contracts", strings.Join(ev.Interfaces, ", ")},
		{"Listeners", fmt.Sprintf("%d (%d queued)", len(ev.Listeners), countQueued(ev.Listeners))},
	})

	snippet := dispatchSnippet(ev.Class, ev.Params, "event")
	d.needSpace(16 + d.codeHeight(snippet))
	d.h2("How to dispatch it")
	d.code(snippet)
	if len(from) > 0 {
		d.para("Where the app dispatches it today:")
		rows := [][]string{}
		for _, l := range from {
			rows = append(rows, []string{fmt.Sprintf("%s:%d", l.File, l.Line), l.Code})
		}
		d.table([]string{"Place", "Code"}, []float64{58, 116}, rows)
	}

	d.h2("Data it carries")
	if len(ev.Params) == 0 {
		d.para("No constructor parameters.")
	} else {
		d.table([]string{"Name", "Type", "Notes"}, []float64{40, 62, 72}, paramRows(ev.Params))
	}

	d.h2("Listeners, in order")
	if len(ev.Listeners) == 0 {
		d.para("Nothing listens to it yet: dispatching it has no effect until a listener is registered.")
	} else {
		rows := [][]string{}
		for i, l := range ev.Listeners {
			how := "Runs right away, inside the dispatch"
			if l.Queued {
				how = "Queued"
				if q, ok := l.Queue.(string); ok && q != "" {
					how += " on " + q
				}
				how += ": needs a queue worker"
			}
			rows = append(rows, []string{fmt.Sprintf("%d. %s", i+1, l.Name), how, firstNonEmpty(l.Doc, l.File)})
		}
		d.table([]string{"Listener", "How it runs", "About"}, []float64{70, 52, 52}, rows)
	}

	if trace != nil {
		traceSections(d, *trace, ev.Class)
	}

	d.h2("Things to know")
	notes := []string{}
	if countQueued(ev.Listeners) > 0 {
		notes = append(notes, "Queued listeners only run when a worker processes their queue (php artisan queue:work). Locally, start one from LaraMonster's Jobs & Queues page.")
	}
	for _, p := range ev.Params {
		if p.Kind == "model" {
			notes = append(notes, "It carries Eloquent models. Queued listeners receive them re-fetched from the database, so changes made after dispatching are visible to them.")
			break
		}
	}
	if strings.Contains(strings.Join(ev.Interfaces, ","), "ShouldDispatchAfterCommit") {
		notes = append(notes, "It's dispatched only after the surrounding database transaction commits.")
	}
	if strings.Contains(strings.Join(ev.Interfaces, ","), "ShouldBroadcast") {
		notes = append(notes, "It's also broadcast over websockets.")
	}
	notes = append(notes, "Listeners can stop the chain by returning false; later listeners then don't run.")
	d.bullets(notes)
	return d.bytes()
}

// JobGuide documents a job: what it does in plain words, when it runs, how
// it behaves on the queue, and how to dispatch it.
func JobGuide(site string, j Job, a JobAnalysis, trace *Trace) ([]byte, error) {
	d := newDoc(short(j.Class), "Job guide · "+site, site)
	d.para(a.Summary)
	d.kv([][2]string{
		{"Class", j.Class},
		{"Defined in", fmt.Sprintf("%s:%d", j.File, j.Line)},
		{"Contracts", strings.Join(j.Interfaces, ", ")},
		{"Uses", strings.Join(a.Uses, ", ")},
	})

	d.h2("What it does")
	if len(a.Does) == 0 {
		d.para("Its handle() method doesn't use anything LaraMonster recognises; see the code at the end.")
	} else {
		steps := []string{}
		for _, s := range a.Does {
			steps = append(steps, s.Text)
		}
		d.bullets(steps)
	}

	d.h2("When it runs")
	d.bullets(a.Runs)
	if len(a.From) > 0 {
		rows := [][]string{}
		for _, l := range a.From {
			rows = append(rows, []string{fmt.Sprintf("%s:%d", l.File, l.Line), l.Code})
		}
		d.table([]string{"Dispatched from", "Code"}, []float64{58, 116}, rows)
	}

	d.h2("On the queue")
	d.bullets(a.Queue)
	if len(a.Warnings) > 0 {
		d.bullets(a.Warnings)
	}

	snippet := dispatchSnippet(j.Class, j.Params, "job")
	d.needSpace(16 + d.codeHeight(snippet))
	d.h2("How to dispatch it")
	d.code(snippet)
	if len(j.Params) > 0 {
		d.table([]string{"Parameter", "Type", "Notes"}, []float64{40, 62, 72}, paramRows(j.Params))
	}

	if trace != nil {
		traceSections(d, *trace, "")
	}

	code := dedent(j.HandleSource)
	d.needSpace(16 + min(d.codeHeight(code), 60))
	d.h2("The code it runs")
	d.code(code)
	return d.bytes()
}

// TraceReport documents one recorded request, command or job.
func TraceReport(site string, t Trace) ([]byte, error) {
	d := newDoc(t.Title, "Trace · "+site, site)
	traceSections(d, t, "")
	return d.bytes()
}

func traceSections(d *doc, t Trace, focus string) {
	d.h2("What happened in a real run")
	status := fmt.Sprint(t.Status)
	if t.Status == nil {
		status = "-"
	}
	d.kv([][2]string{
		{"Run", t.Title},
		{"Kind", t.Kind},
		{"Started", t.StartedAt},
		{"Result", status},
		{"Duration", fmt.Sprintf("%.1f ms · %d queries · %.1f MB", t.Duration, t.Queries, float64(t.Memory)/(1<<20))},
		{"Route", strings.TrimSpace(t.Route + " " + t.Action)},
	})
	if present(t.Exception) {
		d.para("It failed: " + exceptionLine(t.Exception))
	}
	rows := [][]string{}
	for _, e := range t.Events {
		dur := "-"
		if e.Duration != nil {
			dur = fmt.Sprintf("%.2f ms", *e.Duration)
		}
		name := strings.Repeat("   ", e.Depth) + e.Name
		if e.Depth > 0 {
			name = strings.Repeat("   ", e.Depth-1) + "-> " + e.Name
		}
		note := e.Source
		if present(e.Exception) {
			note = "FAILED: " + exceptionLine(e.Exception)
		}
		rows = append(rows, []string{fmt.Sprintf("%.1f ms", e.At), name, dur, note})
	}
	d.table([]string{"At", "Event", "Took", "From"}, []float64{18, 86, 20, 50}, rows)

	for _, e := range t.Events {
		if !e.App || (focus != "" && e.Name != focus) {
			continue
		}
		d.h2(short(e.Name) + ": listeners that ran")
		if len(e.Ran) == 0 {
			d.para("No listener ran.")
		} else {
			lr := [][]string{}
			for _, r := range e.Ran {
				res := "-"
				if present(r.Result) {
					res = compactJSON(r.Result, 120)
				}
				if present(r.Exception) {
					res = "FAILED: " + exceptionLine(r.Exception)
				}
				queued := ""
				if r.Queued {
					queued = " (queued)"
				}
				lr = append(lr, []string{r.Name + queued, fmt.Sprintf("%.2f ms", r.Duration), res})
			}
			d.table([]string{"Listener", "Took", "Returned"}, []float64{82, 22, 70}, lr)
		}
		d.para("Payload:")
		d.code(prettyJSON(e.Payload))
		if focus != "" {
			break
		}
	}
}

func dispatchSnippet(class string, params []Param, kind string) string {
	args := []string{}
	for _, p := range params {
		v := "$" + p.Name
		switch p.Kind {
		case "model":
			v = short(p.Class) + "::findOrFail($id)"
		case "int":
			v = "1"
		case "float":
			v = "9.99"
		case "bool":
			v = "true"
		case "string":
			v = "'…'"
		case "array":
			v = "[]"
		}
		if p.Optional {
			continue
		}
		args = append(args, p.Name+": "+v)
	}
	call := fmt.Sprintf("new \\%s(%s)", class, strings.Join(args, ", "))
	if kind == "event" {
		return fmt.Sprintf("use %s;\n\n%s::dispatch(%s);\n// or\nevent(%s);", class, short(class), strings.Join(args, ", "), call)
	}
	return fmt.Sprintf("use %s;\n\n%s::dispatch(%s);\n// right now, without a queue:\n%s::dispatchSync(%s);\n// later, on a specific queue:\n%s::dispatch(%s)->onQueue('…')->delay(now()->addMinutes(5));",
		class, short(class), strings.Join(args, ", "), short(class), strings.Join(args, ", "), short(class), strings.Join(args, ", "))
}

func paramRows(params []Param) [][]string {
	rows := [][]string{}
	for _, p := range params {
		notes := []string{}
		switch p.Kind {
		case "model":
			notes = append(notes, "an Eloquent model ("+short(p.Class)+")")
		case "enum":
			if p.Enum != nil {
				cases := []string{}
				for _, c := range p.Enum.Cases {
					cases = append(cases, fmt.Sprint(c))
				}
				notes = append(notes, "one of: "+strings.Join(cases, ", "))
			}
		}
		if p.Optional {
			notes = append(notes, "optional, default "+compactJSON(p.Default, 40))
		} else if p.Nullable {
			notes = append(notes, "can be null")
		}
		rows = append(rows, []string{"$" + p.Name, p.Type, strings.Join(notes, "; ")})
	}
	return rows
}

func countQueued(ls []EventListener) int {
	n := 0
	for _, l := range ls {
		if l.Queued {
			n++
		}
	}
	return n
}

func exceptionLine(raw json.RawMessage) string {
	var e struct {
		Class, Message, File string
		Line                 int
	}
	_ = json.Unmarshal(raw, &e)
	return fmt.Sprintf("%s: %s (%s:%d)", short(e.Class), e.Message, e.File, e.Line)
}

func prettyJSON(raw json.RawMessage) string {
	var v any
	if json.Unmarshal(raw, &v) != nil {
		return string(raw)
	}
	b, _ := json.MarshalIndent(sortKeys(v), "", "  ")
	s := string(b)
	if lines := strings.Split(s, "\n"); len(lines) > 80 {
		s = strings.Join(lines[:80], "\n") + "\n  …"
	}
	return s
}

func sortKeys(v any) any { // encoding/json already sorts map keys; kept for clarity
	if m, ok := v.(map[string]any); ok {
		keys := make([]string, 0, len(m))
		for k := range m {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			m[k] = sortKeys(m[k])
		}
	}
	return v
}

func compactJSON(raw json.RawMessage, max int) string {
	var buf bytes.Buffer
	if json.Compact(&buf, raw) != nil {
		return string(raw)
	}
	s := buf.String()
	if len(s) > max {
		s = s[:max] + "…"
	}
	return s
}

func dedent(src string) string {
	lines := strings.Split(strings.TrimRight(src, "\n"), "\n")
	minIndent := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " \t"))
		if minIndent < 0 || n < minIndent {
			minIndent = n
		}
	}
	for i, l := range lines {
		if len(l) >= minIndent && minIndent > 0 {
			lines[i] = l[minIndent:]
		}
	}
	return strings.Join(lines, "\n")
}

// present reports whether a raw JSON value holds something (not absent or null).
func present(raw json.RawMessage) bool {
	return len(raw) > 0 && string(raw) != "null"
}

func firstNonEmpty(xs ...string) string {
	for _, x := range xs {
		if strings.TrimSpace(x) != "" {
			return x
		}
	}
	return ""
}
