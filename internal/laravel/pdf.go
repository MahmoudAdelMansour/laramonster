// Event is an event class as the runner found it.
type Event struct {
	Class      string          `json:"class"`
	File       string          `json:"file"`
	Line       int             `json:"line"`
	Doc        string          `json:"doc,omitempty"`
	Params     []Param         `json:"params"`
	Interfaces []string        `json:"interfaces"`
	Listeners  []EventListener `json:"listeners"`
}

type EventListener struct {
	Name       string `json:"name"`
	Queued     bool   `json:"queued"`
	File       string `json:"file,omitempty"`
	Doc        string `json:"doc,omitempty"`
	Queue      any    `json:"queue,omitempty"`
	Connection any    `json:"connection,omitempty"`
}

// ── a small document builder on top of fpdf ──────────────────────────────────

type doc struct {
	pdf *fpdf.Fpdf
	tr  func(string) string
}

var (
	brand = [3]int{79, 79, 255}
	ink   = [3]int{28, 38, 64}
	body  = [3]int{61, 71, 94}
	muted = [3]int{100, 107, 125}
	line  = [3]int{223, 226, 234}
	wash  = [3]int{243, 245, 250}
)

func newDoc(title, subtitle, site string) *doc {
	p := fpdf.New("P", "mm", "A4", "")
	p.SetMargins(18, 18, 18)
	p.SetAutoPageBreak(true, 20)
	d := &doc{pdf: p, tr: p.UnicodeTranslatorFromDescriptor("")}
	generated := time.Now().Format("2 Jan 2006 15:04")
	p.SetFooterFunc(func() {
		p.SetY(-14)
		p.SetFont("Helvetica", "", 8)
		p.SetTextColor(muted[0], muted[1], muted[2])
		p.CellFormat(0, 6, d.tr(fmt.Sprintf("%s · generated by LaraMonster Pro on %s", site, generated)), "", 0, "L", false, 0, "")
		p.CellFormat(0, 6, fmt.Sprintf("%d / {nb}", p.PageNo()), "", 0, "R", false, 0, "")
	})
	p.AliasNbPages("{nb}")
	p.AddPage()

	// Title band.
	p.SetFillColor(brand[0], brand[1], brand[2])
	p.Rect(0, 0, 210, 38, "F")
	p.SetXY(18, 10)
	p.SetTextColor(220, 222, 255)
	p.SetFont("Helvetica", "B", 9)
	p.CellFormat(0, 5, d.tr(strings.ToUpper(subtitle)), "", 1, "L", false, 0, "")
	p.SetX(18)
	p.SetTextColor(255, 255, 255)
	p.SetFont("Helvetica", "B", 19)
	p.MultiCell(174, 9, d.tr(title), "", "L", false)
	p.SetY(46)
	return d
}

func (d *doc) h2(text string) {
	p := d.pdf
	if p.GetY() > 238 { // keep a heading with what follows it
		p.AddPage()
	}
	p.Ln(4)
	p.SetFont("Helvetica", "B", 13)
	p.SetTextColor(ink[0], ink[1], ink[2])
	p.CellFormat(0, 8, d.tr(text), "", 1, "L", false, 0, "")
	p.SetDrawColor(brand[0], brand[1], brand[2])
	p.SetLineWidth(0.6)
	p.Line(18, p.GetY(), 34, p.GetY())
	p.Ln(3)
}

func (d *doc) para(text string) {
	p := d.pdf
	p.SetFont("Helvetica", "", 10)
	p.SetTextColor(body[0], body[1], body[2])
	p.MultiCell(0, 5.2, d.tr(text), "", "L", false)
	p.Ln(1.5)
}

func (d *doc) muted(text string) {
	p := d.pdf
	p.SetFont("Helvetica", "", 8.5)
	p.SetTextColor(muted[0], muted[1], muted[2])
	p.MultiCell(0, 4.6, d.tr(text), "", "L", false)
	p.Ln(1)
}

func (d *doc) bullets(items []string) {
	p := d.pdf
	p.SetFont("Helvetica", "", 10)
	for _, it := range items {
		p.SetTextColor(brand[0], brand[1], brand[2])
		p.CellFormat(5, 5.2, d.tr("•"), "", 0, "L", false, 0, "")
		p.SetTextColor(body[0], body[1], body[2])
		p.MultiCell(0, 5.2, d.tr(it), "", "L", false)
		p.Ln(0.6)
	}
	p.Ln(1)
}

// kv is a two-column fact table.
func (d *doc) kv(rows [][2]string) {
	p := d.pdf
	for _, r := range rows {
		if r[1] == "" {
			continue
		}
		if p.GetY() > 268 {
			p.AddPage()
		}
		y, page := p.GetY(), p.PageNo()
		p.SetFont("Helvetica", "B", 9)
		p.SetTextColor(muted[0], muted[1], muted[2])
		p.CellFormat(40, 5.4, d.tr(r[0]), "", 0, "L", false, 0, "")
		p.SetFont("Helvetica", "", 9.5)
		p.SetTextColor(ink[0], ink[1], ink[2])
		p.MultiCell(0, 5.4, d.tr(r[1]), "", "L", false)
		if p.PageNo() == page && p.GetY() < y+5.4 {
			p.SetY(y + 5.4)
		}
	}
	p.Ln(2)
}

// table draws a header row and rows; widths in mm (sum ≤ 174).
func (d *doc) table(head []string, widths []float64, rows [][]string) {
	p := d.pdf
	p.SetFont("Helvetica", "B", 8.5)
	p.SetFillColor(wash[0], wash[1], wash[2])
	p.SetTextColor(muted[0], muted[1], muted[2])
	for i, h := range head {
		p.CellFormat(widths[i], 7, d.tr(strings.ToUpper(h)), "", 0, "L", true, 0, "")
	}
	p.Ln(-1)
	p.SetFont("Helvetica", "", 9)
	p.SetDrawColor(line[0], line[1], line[2])
	p.SetLineWidth(0.2)
	for _, r := range rows {
		// Row height from the tallest wrapped cell.
		lines := 1
		for i, c := range r {
			if n := len(p.SplitLines([]byte(d.tr(c)), widths[i]-2)); n > lines {
				lines = n
			}
		}
		h := float64(lines)*4.6 + 2.4
		if p.GetY()+h > 277 {
			p.AddPage()
		}
		x, y := p.GetX(), p.GetY()
		for i, c := range r {
			p.SetXY(x, y+1.2)
			p.SetTextColor(ink[0], ink[1], ink[2])
			if i > 0 {
				p.SetTextColor(body[0], body[1], body[2])
			}
			p.MultiCell(widths[i], 4.6, d.tr(c), "", "L", false)
			x += widths[i]
		}
		p.SetXY(18, y+h)
		p.Line(18, y+h, 18+sum(widths), y+h)
	}
	p.Ln(3)
}

func (d *doc) code(text string) {
	p := d.pdf
	text = strings.TrimRight(text, "\n")
	if text == "" {
		return
	}
	p.SetFont("Courier", "", 8.4)
	lines := p.SplitLines([]byte(d.tr(text)), 168)
	h := float64(len(lines))*4 + 5
	if p.GetY()+min(h, 50) > 277 {
		p.AddPage()
	}
	p.SetFillColor(wash[0], wash[1], wash[2])
	p.SetTextColor(ink[0], ink[1], ink[2])
	p.SetX(18)
	p.MultiCell(174, 4, d.tr(text), "", "L", true)
	p.Ln(3)
}

// needSpace starts a new page unless mm millimetres fit on this one.
func (d *doc) needSpace(mm float64) {
	if d.pdf.GetY()+mm > 277 {
		d.pdf.AddPage()
	}
}

func (d *doc) codeHeight(text string) float64 {
	d.pdf.SetFont("Courier", "", 8.4)
	return float64(len(d.pdf.SplitLines([]byte(d.tr(strings.TrimRight(text, "\n"))), 168)))*4 + 5
}

func (d *doc) bytes() ([]byte, error) {
	var buf bytes.Buffer
	if err := d.pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func sum(xs []float64) float64 {
	t := 0.0
	for _, x := range xs {
		t += x
	}
	return t
}

